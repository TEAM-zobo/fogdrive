    base <= 30 -> Triple(30, 30, 50)
    base <= 40 -> Triple(30, 40, 50)
    base <= 50 -> Triple(30, 50, 60)
    base <= 60 -> Triple(50, 60, 80)
    base <= 80 -> Triple(60, 80, 100)
    else -> Triple(80, 100, 110)
}

