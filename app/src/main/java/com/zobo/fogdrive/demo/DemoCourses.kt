/**
 * One scripted demo drive: a real road path (OSRM, © OpenStreetMap contributors), its destination
 * (for the detour suggestion and the arrival), and what the car "does" on the way. Each course
 * shows different stamps: rain and a rear passenger, night lights, a navigation arrival.
 */
class DemoCourse(
    val id: String,
    val title: String,
    val summary: String,
    val destination: Place,
    val route: List<Pair<Double, Double>>,
    /** Wipers on between these fractions of the route (빗속 개척), if set. */
    val rain: ClosedFloatingPointRange<Double>? = null,
    /** Low beams on for the whole drive (야간 개척). */
    val lowBeam: Boolean = false,
    /** Someone in the rear seat (가족 탐험). */
    val rearPassenger: Boolean = false,
    /** Speed limit shown by the stand-in guidance, km/h. */
    val speedLimit: Int = 50,
) {
    /** Distance along [route] at each of its points, in metres. */
    val along: List<Double> = route.indices.runningFold(0.0) { acc, i ->
        if (i == 0) acc else acc + Tiles.distanceMeters(route[i - 1].first, route[i - 1].second, route[i].first, route[i].second)
    }.drop(1)

    val lengthMeters: Double get() = along.last()

    /** The same road back to [DemoCourses.START], for a round trip. */
    fun returnTrip(): DemoCourse = DemoCourse(
        id = "$id-back", title = "$title · 복귀", summary = summary, destination = DemoCourses.START,
        route = route.reversed(), rain = rain, lowBeam = lowBeam, rearPassenger = rearPassenger, speedLimit = speedLimit,
    )

    /** Route points where the heading swings by more than 35°, as (distance along, turn). */
    val turns: List<Pair<Double, TurnKind>> = (1 until route.size - 1).mapNotNull { i ->
        var delta = bearing(route[i], route[i + 1]) - bearing(route[i - 1], route[i])
        if (delta > 180) delta -= 360
        if (delta < -180) delta += 360
        val kind = when {
            abs(delta) > 150 -> TurnKind.UTURN
            delta > 35 -> TurnKind.RIGHT
            delta < -35 -> TurnKind.LEFT
            else -> null
        }
        kind?.let { along[i] to it }
    }

    private fun bearing(a: Pair<Double, Double>, b: Pair<Double, Double>): Double {
        val dy = b.first - a.first
        val dx = (b.second - a.second) * cos(Math.toRadians(a.first))
        return Math.toDegrees(atan2(dx, dy))
    }
}

