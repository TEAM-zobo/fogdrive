def kt_bool(v):
    return "true" if v else "false"


def main():
    data = json.load(open(os.path.join(HERE, "routes.json"), encoding="utf-8"))
    home = data["places"]["home"]
    src = open(KT, encoding="utf-8").read()
    start = src.index("/**\n * Each route lives in its own holder object")
    end = src.index("/** Lower, usual and higher limit")
    out = []
    out.append('''/**
 * Each route lives in its own holder object: the coordinates are hundreds of literals, which
 * would overflow one class initializer's 64 KB limit. ([all] still touches every holder, so all
 * routes are built together the first time [DemoCourses] is used.)
 *
 * Generated by tools/demo/persona/gen_courses.py from the demo persona's routes (a driver living in
 * 위례 who commutes to 현대자동차 본사); edit that script, not this object.
 */
object DemoCourses {
''')
    out.append(f'    /** Every course leaves from here (the demo persona\'s home, 송파꿈에그린 위례24단지), as does the map before the first fix. */\n')
    out.append(f'    val START = Place("집", {home[0]:.5f}, {home[1]:.5f}, "서울 송파구 위례광장로 121")\n\n')
    for cid, key, *_ in COURSES:
        pts = data["routes"][key]
        name = "".join(p.capitalize() for p in cid.split("-")) + "Route"
        out.append(f"    private object {name} {{\n        val points: List<Pair<Double, Double>> = listOf(\n")
        out += [f"            {lat:.5f} to {lng:.5f},\n" for lat, lng in pts]
        out.append("        )\n    }\n\n")
    out.append("    val all: List<DemoCourse> = listOf(\n")
    for cid, key, title, summary, (dname, daddr), opt in COURSES:
        dest = data["places"].get(key) or data["routes"][key][-1]  # a leg not from home ends at its last point
        name = "".join(p.capitalize() for p in cid.split("-")) + "Route"
        out.append("        DemoCourse(\n")
        out.append(f'            id = "{cid}",\n            title = "{title}",\n            summary = "{summary}",\n')
        out.append(f'            destination = Place("{dname}", {dest[0]:.5f}, {dest[1]:.5f}, "{daddr}"),\n')
        out.append(f"            route = {name}.points,\n")
        for k, v in opt.items():
            out.append(f"            {k} = {kt_bool(v) if isinstance(v, bool) else v},\n")
        out.append("        ),\n")
    out.append("    )\n\n    fun byId(id: String?): DemoCourse = all.firstOrNull { it.id == id } ?: all.first()\n}\n\n")
    src = src[:start] + "".join(out) + src[end:]
    open(KT, "w", encoding="utf-8").write(src)
    print(f"{os.path.relpath(KT, ROOT)}: {len(COURSES)} courses")


if __name__ == "__main__":
    main()
